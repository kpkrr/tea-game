CUT_SCALE = 2
CUT_FEATHER = 60   # Gaussian sigma, plate px: soft edge (owner pick S2)
CUT_FEATHER_LOW = 170           # wider fade toward the stairs (owner)
CUT_LOW_FROM, CUT_LOW_TO = 2550, 3000
CUT_EDGE_FADE = 260             # plate px: mask fades out toward the plate's side edges   # plate y where the edge goes from CUT_FEATHER to CUT_FEATHER_LOW


def build() -> Image.Image:
	w, h = PLATE[0] // SCALE, PLATE[1] // SCALE
	m = Image.new("L", (w, h), 0)
	ImageDraw.Draw(m).polygon([(x / SCALE, y / SCALE) for x, y in KITCHEN], fill=255)
	k = np.asarray(m.filter(ImageFilter.GaussianBlur(KITCHEN_FEATHER / SCALE)), dtype=np.float32) / 255
	light = k * KITCHEN_LEVEL
	ys, xs = np.mgrid[0:h, 0:w].astype(np.float32) * SCALE
	for cx, cy, r, s in POOLS:
		d = np.sqrt((xs - cx) ** 2 + (ys - cy) ** 2)
		light = np.maximum(light, s * np.clip(1 - d / r, 0, 1) ** FALLOFF)
	return Image.fromarray((np.clip(light, 0, 1) * 255).astype(np.uint8))


def build_cut() -> Image.Image:
	m = Image.new("L", (PLATE[0] // CUT_SCALE, PLATE[1] // CUT_SCALE), 0)
	ImageDraw.Draw(m).polygon([(x / CUT_SCALE, y / CUT_SCALE) for x, y in KITCHEN_CUT], fill=255)
	tight = np.asarray(m.filter(ImageFilter.GaussianBlur(CUT_FEATHER / CUT_SCALE)), dtype=np.float32)
	wide = np.asarray(m.filter(ImageFilter.GaussianBlur(CUT_FEATHER_LOW / CUT_SCALE)), dtype=np.float32)
	y = np.arange(m.height, dtype=np.float32)[:, None] * CUT_SCALE
	t = np.clip((y - CUT_LOW_FROM) / (CUT_LOW_TO - CUT_LOW_FROM), 0, 1)
	t = t * t * (3 - 2 * t)
	out = tight * (1 - t) + wide * t
	# Fade to 0 toward the plate's left/right edges: beyond them the frame is always
	# blurred, so a mask still >0 at the edge would show as a hard vertical band.
	x = np.arange(m.width, dtype=np.float32)[None, :] * CUT_SCALE
	e = np.clip(np.minimum(x, PLATE[0] - x) / CUT_EDGE_FADE, 0, 1)
	out *= e * e * (3 - 2 * e)
	return Image.fromarray(np.clip(out, 0, 255).astype(np.uint8))


